import { FlaskConical, X } from 'lucide-react';
import { useState } from 'react';

export function SimBanner() {
  const [dismissed, setDismissed] = useState(false);
  if (dismissed) return null;
  return (
    <div className="flex-shrink-0 flex items-center gap-3 px-5 py-2 bg-amber-950/60 border-b border-amber-800/40 text-amber-300 text-xs">
      <FlaskConical className="w-3.5 h-3.5 flex-shrink-0 text-amber-400" />
      <span>
        <strong className="font-semibold">Simulated Data Only.</strong>{' '}
        All pollution values, exposure estimates, and hotspot rankings are generated by a
        simulation engine for demonstration purposes. No real monitoring instruments were used.
        Do not use for health or policy decisions.
      </span>
      <button
        onClick={() => setDismissed(true)}
        className="ml-auto text-amber-500 hover:text-amber-300 transition-colors flex-shrink-0"
        aria-label="Dismiss banner"
      >
        <X className="w-3.5 h-3.5" />
      </button>
    </div>
  );
}
