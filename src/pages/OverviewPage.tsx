import { useEffect, useState } from 'react';
import { mockRailairService } from '../services/mockRailairService';
import type { KpiSummary, TrendDataPoint, DataQualityItem } from '../types/railair';
import { KpiCards } from '../components/KpiCards';
import { TrendChart } from '../components/TrendChart';
import { DataQualityTable } from '../components/DataQualityTable';
import { RefreshCw, Info } from 'lucide-react';
import { formatISOTimestamp } from '../lib/formatters';

export function OverviewPage() {
  const [kpi, setKpi] = useState<KpiSummary | null>(null);
  const [trend, setTrend] = useState<TrendDataPoint[]>([]);
  const [quality, setQuality] = useState<DataQualityItem[]>([]);
  const [loading, setLoading] = useState(true);

  async function load() {
    setLoading(true);
    const [k, t, q] = await Promise.all([
      mockRailairService.getKpiSummary(),
      mockRailairService.getTrend(),
      mockRailairService.getDataQuality(),
    ]);
    setKpi(k);
    setTrend(t);
    setQuality(q);
    setLoading(false);
  }

  useEffect(() => { load(); }, []);

  return (
    <div className="p-5 space-y-5 max-w-6xl mx-auto">
      {/* Header row */}
      <div className="flex items-center justify-between">
        <div>
          <h2 className="text-lg font-semibold text-white">Corridor Air Quality Overview</h2>
          <p className="text-xs text-slate-400 mt-0.5">
            Meerut City → New Delhi · 83 km · 7 stations ·{' '}
            {kpi ? formatISOTimestamp(kpi.timestamp) : '—'}
          </p>
        </div>
        <button
          onClick={load}
          disabled={loading}
          className="flex items-center gap-1.5 text-xs text-slate-400 hover:text-slate-200 transition-colors"
        >
          <RefreshCw className={`w-3.5 h-3.5 ${loading ? 'animate-spin' : ''}`} />
          Refresh
        </button>
      </div>

      {/* Simulated notice */}
      <div className="flex items-start gap-2 p-3 rounded-lg bg-amber-950/40 border border-amber-800/40 text-amber-300 text-xs">
        <Info className="w-4 h-4 flex-shrink-0 mt-0.5" />
        <span>
          All KPI values shown below are <strong>simulated</strong> by the RailAir Intelligence Simulation Engine v0.1.
          They do not reflect real-time or historical monitored data. Coverage (28%) indicates that only 2 of the 7 stations
          have any plausible real-world reference; the rest are interpolated.
        </span>
      </div>

      {/* KPI cards */}
      {loading ? (
        <div className="grid grid-cols-2 lg:grid-cols-4 gap-3">
          {[0, 1, 2, 3].map((i) => (
            <div key={i} className="bg-navy-700 rounded-xl border border-navy-500 h-24 animate-pulse" />
          ))}
        </div>
      ) : kpi ? (
        <KpiCards kpi={kpi} />
      ) : null}

      {/* Trend chart */}
      <div className="bg-navy-800 rounded-xl border border-navy-500 p-4">
        <div className="flex items-center justify-between mb-3">
          <h3 className="text-sm font-semibold text-slate-200">24-Hour Simulated Trend</h3>
          <span className="badge-simulated">SIMULATED</span>
        </div>
        <p className="text-xs text-slate-400 mb-3">
          Illustrative 24-hour diurnal pattern for corridor-average PM concentrations. Peak around morning
          rush (08:00) and evening (20:00) is typical for Indo-Gangetic Plain urban environments — but these
          specific values are generated by the simulation engine.
        </p>
        {loading ? (
          <div className="h-56 bg-navy-700 rounded animate-pulse" />
        ) : (
          <TrendChart data={trend} />
        )}
      </div>

      {/* Data Quality */}
      <div className="bg-navy-800 rounded-xl border border-navy-500 p-4">
        <div className="flex items-center justify-between mb-3">
          <h3 className="text-sm font-semibold text-slate-200">Data Sources &amp; Quality</h3>
        </div>
        <p className="text-xs text-slate-400 mb-3">
          The table below shows data provenance metadata. "Measured" and "Modelled" rows are illustrative
          placeholders referencing the kind of data that would augment a real system.
        </p>
        {loading ? (
          <div className="h-24 bg-navy-700 rounded animate-pulse" />
        ) : (
          <DataQualityTable items={quality} />
        )}
      </div>

      {/* WHO guideline callout */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
        <div className="p-4 rounded-xl border border-navy-500 bg-navy-800">
          <h4 className="text-xs font-semibold text-slate-300 mb-2 uppercase tracking-wider">WHO PM2.5 Guideline</h4>
          <div className="text-2xl font-bold font-mono text-cyan-400">15 µg/m³</div>
          <p className="text-xs text-slate-400 mt-1">Annual mean (2021 guidelines). Corridor simulated average is {kpi ? `${kpi.avgPm25} µg/m³` : '—'} — approximately {kpi ? `${Math.round(kpi.avgPm25 / 15)}×` : '—'} above this limit.</p>
        </div>
        <div className="p-4 rounded-xl border border-navy-500 bg-navy-800">
          <h4 className="text-xs font-semibold text-slate-300 mb-2 uppercase tracking-wider">India NAAQS PM2.5</h4>
          <div className="text-2xl font-bold font-mono text-teal-400">60 µg/m³</div>
          <p className="text-xs text-slate-400 mt-1">24-hour standard. Corridor simulated average is {kpi ? `${Math.round((kpi.avgPm25 / 60 - 1) * 100)}%` : '—'} above this standard.</p>
        </div>
      </div>
    </div>
  );
}
